"""Reports the size of each RAG's downloaded corpus: document/snippet counts,
words, characters, and a rough token estimate (words x 1.35, a common rule of
thumb; not a real tokenizer count).

Run from the repo root, after scripts/prepare_corpora.py:
    python scripts/corpus_stats.py                 # every RAG with a corpus on disk
    python scripts/corpus_stats.py lightrag raptor  # just these
    python scripts/corpus_stats.py --markdown       # print a Markdown table (for pasting into the README)
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import ROOT, corpus_tag, load_config
from src.rags.registry import RAG_NAMES, get_rag

TOKENS_PER_WORD = 1.35  # rough rule of thumb; report this as approximate in the paper


def stats_for(rag_name, cfg):
    docs = get_rag(rag_name, cfg).load_corpus()
    if not docs:
        return None
    words = [len(d["text"].split()) for d in docs]
    chars = [len(d["text"]) for d in docs]
    groups = {d.get("group") or d.get("title") or d["id"] for d in docs}
    total_words = sum(words)
    return {
        "rag": rag_name,
        "corpus": corpus_tag(cfg, rag_name),
        "n_documents": len(docs),
        "n_source_files": len(groups),  # distinct documents/textbooks a snippet-style corpus is grouped into
        "total_words": total_words,
        "total_chars": sum(chars),
        "approx_tokens": round(total_words * TOKENS_PER_WORD),
        "avg_words_per_document": round(total_words / len(docs), 1),
        "min_words": min(words),
        "max_words": max(words),
    }


def as_markdown_row(s):
    return (
        f"| {s['rag']} | {s['corpus']} | {s['n_documents']:,} | {s['n_source_files']:,} | "
        f"{s['total_words']:,} | {s['approx_tokens']:,} | {s['avg_words_per_document']:,} |"
    )


def main():
    ap = argparse.ArgumentParser()
    # NOTE: nargs="*" combined with choices= mis-validates the empty default list
    # itself against choices (an argparse quirk), so choices are checked by hand below.
    ap.add_argument("rags", nargs="*", default=[])
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--save", action="store_true", help="also write results/corpus_stats.json and .md")
    args = ap.parse_args()
    bad = [r for r in args.rags if r not in RAG_NAMES]
    if bad:
        ap.error(f"invalid choice(s): {bad} (choose from {RAG_NAMES})")

    cfg = load_config()
    results = []
    for rag in args.rags or RAG_NAMES:
        s = stats_for(rag, cfg)
        if s is None:
            print(f"{rag}: no corpus on disk yet. Run: python scripts/prepare_corpora.py {rag}")
            continue
        results.append(s)
        if not args.markdown:
            print(f"\n{rag} ({s['corpus']}):")
            print(f"  {s['n_documents']:,} document(s)/snippet(s), from {s['n_source_files']:,} source file(s)")
            print(f"  {s['total_words']:,} words, {s['total_chars']:,} characters, "
                  f"~{s['approx_tokens']:,} tokens")
            print(f"  {s['avg_words_per_document']:,} words/document on average "
                  f"(range {s['min_words']}-{s['max_words']})")

    if not results:
        sys.exit("No corpora found. Run scripts/prepare_corpora.py first.")

    if args.markdown or args.save:
        lines = [
            "| RAG | Corpus | Documents/snippets | Source files | Words | Approx. tokens | Avg words/doc |",
            "|---|---|---|---|---|---|---|",
        ] + [as_markdown_row(s) for s in results]
        table = "\n".join(lines)
        if args.markdown:
            print(table)
        if args.save:
            out_dir = ROOT / "results"
            out_dir.mkdir(parents=True, exist_ok=True)
            (out_dir / "corpus_stats.json").write_text(json.dumps(results, indent=2))
            (out_dir / "corpus_stats.md").write_text(
                f"Generated by `python scripts/corpus_stats.py --save`. "
                f"Token counts are approximate (words x {TOKENS_PER_WORD}).\n\n{table}\n"
            )
            print(f"\nSaved to {out_dir}/corpus_stats.json and corpus_stats.md")


if __name__ == "__main__":
    main()
